import {test} from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {openStore} from '../src/store.mjs';
import {openAuth,PERMISSIONS} from '../src/auth.mjs';
import {openCash} from '../src/cash.mjs';
import {openCashAdjustments} from '../src/cash-adjustments.mjs';
import {inspectRefundStockSync} from '../src/refund-sync-readiness.mjs';
import {openSync} from '../src/sync.mjs';
import {reconcile} from '../src/reconcile.mjs';
const cloudConfig={endpoint:'https://example.supabase.co/functions/v1/zhirox-sync',market_id:'11111111-1111-4111-8111-111111111111',device_id:'22222222-2222-4222-8222-222222222222',token:'x'.repeat(43)};
function make(t){
 const store=openStore(':memory:');openAuth(store.db);t.after(()=>store.close());
 store.db.prepare('INSERT INTO auth_users VALUES(?,?,?,?,?,?,?,?)').run('owner','Owner','owner','hash','salt','owner',1,Date.now());
 const owner={user:{id:'owner',permissions:PERMISSIONS.owner}};
 const product=store.create({name:'QA شیر',sku:'QA-RET-31',currency:'IQD',unit_price:1450,unit_cost:900,carton_units:6,carton_price:8500,stock_milli:20000,barcodes:[]});
 const cash=openCash(store),actions=openCashAdjustments(store);
 store.attachSaleCashHook((a,s)=>cash.recordSale(a,s));
 cash.open(owner,{request_id:randomUUID(),currency:'IQD',opening_amount:10000});
 const sale=store.sell({request_id:randomUUID(),currency:'IQD',received:3000,items:[{product_id:product.id,unit:'unit',quantity:2}]},'owner');
 return{store,owner,product,cash,actions,sale};
}
test('full refund queues exactly one stock-only redacted event; expense remains local-only',t=>{
 const f=make(t);
 const before=f.store.db.prepare("SELECT count(*) n FROM outbox").get().n;
 const request={request_id:randomUUID(),currency:'IQD',reason:'QA گەڕاندنەوەی تەواوی کاڵا'};
 const refund=f.actions.refund(f.owner,f.sale.id,request);
 const expense=f.actions.expense(f.owner,{request_id:randomUUID(),currency:'IQD',amount:125,reason:'QA خەرجیی بەڵگەنامە'});
 assert.equal(refund.replayed,false);assert.equal(expense.replayed,false);
 assert.equal(f.store.db.prepare('SELECT count(*) n FROM outbox').get().n,before+1);
 assert.equal(f.store.db.prepare("SELECT count(*) n FROM outbox WHERE kind='stock.refund_created'").get().n,1);
 assert.equal(f.actions.refund(f.owner,f.sale.id,request).replayed,true);
 assert.equal(f.store.db.prepare('SELECT count(*) n FROM outbox').get().n,before+1);
 const preview=inspectRefundStockSync(f.store.db);
 assert.equal(preview.contract_ready,true,JSON.stringify(preview));
 assert.equal(preview.remote_protocol_verified,false);
 assert.equal(preview.remote_posting_allowed,false);
 assert.equal(preview.live_network_requests,0);
 assert.equal(preview.local_only_cash_ledger,true);
 assert.equal(preview.refunds,1);
 assert.equal(preview.expenses_local_only,1);
 assert.equal(preview.staged_refunds,1);
 assert.equal(preview.missing_events,0);
 assert.equal(preview.inventory_events.length,1);
 assert.equal(preview.inventory_events[0].ledger.length,1);
 assert.equal(preview.inventory_events[0].ledger[0].delta_milli,2000);
 const asText=JSON.stringify(preview.inventory_events);
 for(const secret of ['amount','currency','reason','actor','shift','expense','2900','125','QA خەرجی'])assert.equal(asText.includes(secret),false,'No money/private detail in remote event: '+secret);
 assert.equal(reconcile(f.store.db).ok,true);
});
test('refund rollback never leaves phantom stock-return queue entry',t=>{
 const f=make(t),before=f.store.db.prepare('SELECT count(*) n FROM outbox').get().n;
 assert.throws(()=>f.actions.refund(f.owner,f.sale.id,{request_id:randomUUID(),currency:'IQD',reason:'QA fails rollback'},()=>{throw Error('force rollback');}),/force rollback/);
 assert.equal(f.store.db.prepare('SELECT count(*) n FROM outbox').get().n,before);
 assert.equal(f.store.db.prepare('SELECT count(*) n FROM cash_adjustments').get().n,0);
 assert.equal(reconcile(f.store.db).ok,true);
});
test('read-only audit detects missing legacy refund outbox event without auto-backfill',t=>{
 const f=make(t);
 f.actions.refund(f.owner,f.sale.id,{request_id:randomUUID(),currency:'IQD',reason:'QA legacy pending event'});
 const before=f.store.db.prepare('SELECT count(*) n FROM outbox').get().n;
 f.store.db.prepare("DELETE FROM outbox WHERE kind='stock.refund_created'").run();
 const report=inspectRefundStockSync(f.store.db);
 assert.equal(report.contract_ready,false);
 assert.equal(report.reason,'historical_refund_missing_outbox');
 assert.equal(report.missing_events,1);
 assert.equal(report.inventory_events.length,0);
 assert.equal(f.store.db.prepare('SELECT count(*) n FROM outbox').get().n,before-1,'inspection must not mutate DB');
 assert.equal(reconcile(f.store.db).ok,true,'stock/cash ledger remains internally correct but cloud queue missing');
});
test('configured sync refuses to leak stock or cash adjustments and makes zero network requests',async t=>{
 const f=make(t);
 let network=0;
 const sync=openSync(f.store,cloudConfig,{transport:async()=>{network++;throw Error('transport must not be invoked');}});
 f.actions.refund(f.owner,f.sale.id,{request_id:randomUUID(),currency:'IQD',reason:'QA cloud blocked after refund'});
 assert.equal(sync.status().adjustments_blocked,true);
 assert.equal(sync.status().error,'adjustment_protocol_unavailable');
 const pending=sync.status().pending;
 await sync.run({force:true});
 assert.equal(network,0);
 assert.equal(sync.status().pending,pending);
 assert.equal(f.store.db.prepare("SELECT count(*) n FROM outbox WHERE kind='stock.refund_created' AND synced_at IS NULL").get().n,1);
 assert.equal(f.store.db.prepare('SELECT count(*) n FROM cash_adjustments').get().n,1);
});
test('unmodified old installations with no adjustment tables are not blocked from stock-only normal sync',async t=>{
 const s=openStore(':memory:');t.after(()=>s.close());
 let requests=0;
 const sync=openSync(s,cloudConfig,{transport:async()=>{requests++;return{ok:true,json:async()=>({last_sequence:0})};}});
 assert.equal(sync.status().adjustments_blocked,false);
 await sync.run({force:true});
 assert.equal(requests,1);
 assert.equal(sync.status().error,null);
});
