import{test}from'node:test';import assert from'node:assert/strict';
import{randomUUID}from'node:crypto';
import{openStore}from'../src/store.mjs';import{openAuth,PERMISSIONS}from'../src/auth.mjs';
import{openSuppliers}from'../src/suppliers.mjs';import{openCash}from'../src/cash.mjs';import{openPurchases}from'../src/purchases.mjs';
function fixture(t){
 const store=openStore(':memory:');openAuth(store.db);
 for(const role of ['owner','manager','cashier'])store.db.prepare('INSERT INTO auth_users VALUES(?,?,?,?,?,?,?,?)').run(role,role,role,'test','test',role,1,Date.now());
 const session=role=>({user:{id:role,permissions:PERMISSIONS[role]}});
 const supplier=openSuppliers(store).create(session('owner'),{request_id:randomUUID(),code:'STAGE',name:'Stage supplier',currency:'IQD'}).supplier;
 const product=store.create({name:'Milk',sku:'MILK',currency:'IQD',unit_price:2000,unit_cost:1000,carton_units:6,carton_price:11000,stock_milli:5000,barcodes:[]});
 const cash=openCash(store);store.attachSaleCashHook((actor,sale)=>cash.recordSale(actor,sale));
 const purchases=openPurchases(store,{cash});
 const input=()=>({request_id:randomUUID(),supplier_id:supplier.id,currency:'IQD',invoice_no:'TEST',items:[{product_id:product.id,unit:'unit',quantity:2,unit_cost:800}]});
 t.after(()=>store.close());return{store,session,supplier,product,cash,purchases,input};
}
test('persisted purchase intent survives new controller and is posted exactly once',t=>{
 const f=fixture(t),owner=f.session('owner'),arg=f.input(),stock=f.store.get(f.product.id).stock_milli,summary=f.store.summary();
 f.cash.open(owner,{request_id:randomUUID(),currency:'IQD',opening_amount:2000});
 assert.equal(f.purchases.stage(owner,arg).posted,false);
 assert.equal(f.purchases.stage(owner,arg).already_staged,true);
 assert.equal(f.store.get(f.product.id).stock_milli,stock);
 assert.deepEqual(f.store.summary(),summary);
 const recovered=openPurchases(f.store,{cash:f.cash}),list=recovered.listIntents(owner);
 assert.equal(list.pending.length,1);assert.equal(list.pending[0].request_id,arg.request_id);
 assert.equal(list.pending[0].request.items[0].unit_cost,800);
 const committed=recovered.intentPost(owner,arg.request_id);
 assert.equal(committed.replayed,false);assert.equal(committed.purchase.total,1600);
 assert.equal(f.store.get(f.product.id).stock_milli,stock+2000);
 assert.equal(f.cash.status(owner).shifts[0].balance,400);
 assert.equal(recovered.intentPost(owner,arg.request_id).replayed,true);
 assert.equal(f.cash.status(owner).shifts[0].balance,400);
 assert.equal(recovered.listIntents(owner).pending.length,0);
 assert.equal(recovered.listIntents(owner).recently_posted[0].purchase_id,committed.purchase.id);
 assert.throws(()=>recovered.cancelIntent(owner,arg.request_id),e=>e.status===409);
});
test('only one unresolved intent per actor; cancellation is immutable and never changes cash',t=>{
 const f=fixture(t),owner=f.session('owner'),a=f.input(),b=f.input();
 f.cash.open(owner,{request_id:randomUUID(),currency:'IQD',opening_amount:5000});
 f.purchases.stage(owner,a);
 assert.throws(()=>f.purchases.stage(owner,b),e=>e.status===409);
 assert.throws(()=>f.purchases.stage(owner,{...a,invoice_no:'DIFFERENT'}),e=>e.status===409);
 assert.throws(()=>f.purchases.intentPost(f.session('manager'),a.request_id),e=>e.status===403);
 assert.throws(()=>f.purchases.cancelIntent(f.session('manager'),a.request_id),e=>e.status===403);
 assert.throws(()=>f.purchases.stage(f.session('cashier'),b),e=>e.status===403);
 const balance=f.cash.status(owner).shifts[0].balance;
 assert.equal(f.purchases.cancelIntent(owner,a.request_id).cancelled,true);
 assert.equal(f.purchases.cancelIntent(owner,a.request_id).replayed,true);
 assert.throws(()=>f.purchases.stage(owner,a),e=>e.status===409);
 assert.throws(()=>f.purchases.intentPost(owner,a.request_id),e=>e.status===409);
 assert.equal(f.cash.status(owner).shifts[0].balance,balance);
 assert.equal(f.store.db.prepare('SELECT count(*) n FROM purchases').get().n,0);
 assert.equal(f.store.db.prepare('SELECT count(*) n FROM purchase_intent_cancellations').get().n,1);
 assert.equal(f.store.db.prepare("SELECT count(*) n FROM access_audit WHERE action='purchase.intent_cancelled'").get().n,1);
 assert.throws(()=>f.store.db.exec('DELETE FROM purchase_intent_cancellations'),/immutable/);
 assert.equal(f.purchases.listIntents(owner).pending.length,0);
 assert.equal(f.purchases.stage(owner,b).posted,false);
});
test('no cash drawer or insufficient balance never writes a purchase and leaves recoverable intent',t=>{
 const f=fixture(t),owner=f.session('owner'),arg=f.input(),stock=f.store.get(f.product.id).stock_milli;
 f.purchases.stage(owner,arg);
 assert.throws(()=>f.purchases.intentPost(owner,arg.request_id),e=>e.status===409);
 assert.equal(f.purchases.listIntents(owner).pending.length,1);
 f.cash.open(owner,{request_id:randomUUID(),currency:'IQD',opening_amount:1000});
 assert.throws(()=>f.purchases.intentPost(owner,arg.request_id),e=>e.status===409);
 assert.equal(f.store.get(f.product.id).stock_milli,stock);
 assert.equal(f.cash.status(owner).shifts[0].balance,1000);
 assert.equal(f.store.db.prepare('SELECT count(*) n FROM purchases').get().n,0);
 assert.equal(f.purchases.cancelIntent(owner,arg.request_id).cancelled,true);
});
