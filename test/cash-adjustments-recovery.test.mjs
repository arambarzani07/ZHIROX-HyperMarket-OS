import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,mkdirSync,rmSync,readFileSync,existsSync} from 'node:fs';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {randomUUID,createHash} from 'node:crypto';
import {openStore} from '../src/store.mjs';
import {openAuth} from '../src/auth.mjs';
import {openCash} from '../src/cash.mjs';
import {openCashAdjustments} from '../src/cash-adjustments.mjs';
import {openBackups} from '../src/backups.mjs';
import {prepareRecovery} from '../src/recovery.mjs';
import {reconcile} from '../src/reconcile.mjs';
const digest=p=>createHash('sha256').update(readFileSync(p)).digest('hex');
test('full cash refund and expense survive verified copy-only backup without touching live data or original backup',async t=>{
 const root=mkdtempSync(join(tmpdir(),'zhirox-refund-recovery-')),live=join(root,'live'),out=join(root,'restored');
 mkdirSync(live);
 t.after(()=>rmSync(root,{recursive:true,force:true}));
 const store=openStore(join(live,'zhirox.sqlite'));
 const auth=openAuth(store.db);
 const setup=await auth.setup({name:'QA Owner',username:'owner',password:'refund-backup-qa-password'});
 const session=auth.session(setup.token),cash=openCash(store),adjustments=openCashAdjustments(store);
 store.attachSaleCashHook((actor,receipt)=>cash.recordSale(actor,receipt));
 const product=store.create({name:'QA',sku:'REF-REC-1',currency:'IQD',unit_price:2200,unit_cost:1000,carton_units:6,carton_price:13000,stock_milli:10000,barcodes:[]});
 cash.open(session,{request_id:randomUUID(),currency:'IQD',opening_amount:10000});
 const sale=store.sell({request_id:randomUUID(),currency:'IQD',received:5000,items:[{product_id:product.id,unit:'unit',quantity:1}]},setup.user.id);
 adjustments.refund(session,sale.id,{request_id:randomUUID(),currency:'IQD',reason:'گەڕاندنەوەی پشتڕاستکراوی QA'});
 adjustments.expense(session,{request_id:randomUUID(),currency:'IQD',amount:250,reason:'خەرجیی پشکنینی باکئەپ QA'});
 assert.equal(reconcile(store.db).ok,true);
 const history=store.db.prepare('SELECT * FROM cash_adjustments ORDER BY rowid').all();
 const returned=store.db.prepare('SELECT * FROM refund_stock_ledger ORDER BY rowid').all();
 const backup=await store.backup(join(live,'backups'));
 const file=join(live,'backups',backup.name),before=digest(file);
 const verification=await openBackups(join(live,'backups')).verify(backup.name);
 assert.equal(verification.ok,true,JSON.stringify(verification));
 const report=await prepareRecovery({backup:file,output:out,liveDataDir:live});
 assert.equal(report.reconciliation.ok,true);
 assert.equal(report.cloud_sync_enabled,false);
 assert.equal(report.requires_review,true);
 assert.equal(digest(file),before);
 assert.equal(existsSync(join(out,'sync-device.json')),false);
 const copy=openStore(join(out,'zhirox.sqlite'));
 try{
  openAuth(copy.db);openCash(copy);openCashAdjustments(copy);
  assert.deepEqual(copy.db.prepare('SELECT * FROM cash_adjustments ORDER BY rowid').all(),history);
  assert.deepEqual(copy.db.prepare('SELECT * FROM refund_stock_ledger ORDER BY rowid').all(),returned);
  assert.equal(copy.get(product.id).stock_milli,10000);
  assert.equal(copy.db.prepare('SELECT balance FROM cash_shifts WHERE closed_at IS NULL').get().balance,9750);
  assert.equal(reconcile(copy.db).ok,true,JSON.stringify(reconcile(copy.db).failures));
 }finally{copy.close();}
 assert.equal(digest(file),before);
 store.close();
});
