import{test}from'node:test';import assert from'node:assert/strict';
import{mkdtempSync,rmSync,readFileSync,existsSync}from'node:fs';import{tmpdir}from'node:os';
import{join}from'node:path';import{createHash,randomUUID}from'node:crypto';
import{openStore}from'../src/store.mjs';import{openAuth}from'../src/auth.mjs';
import{openSuppliers}from'../src/suppliers.mjs';import{openCash}from'../src/cash.mjs';
import{openPurchases}from'../src/purchases.mjs';import{openBackups}from'../src/backups.mjs';
import{prepareRecovery}from'../src/recovery.mjs';import{reconcile}from'../src/reconcile.mjs';
const hash=path=>createHash('sha256').update(readFileSync(path)).digest('hex');
test('copy-only recovery preserves live cash shifts, immutable movements, pending intents and audit without touching source',async t=>{
 const dir=mkdtempSync(join(tmpdir(),'zhirox-cash-recovery-')),live=join(dir,'live'),out=join(dir,'recovered');
 const {mkdirSync}=await import('node:fs');mkdirSync(live);
 const store=openStore(join(live,'zhirox.sqlite')),auth=openAuth(store.db);
 t.after(()=>{store.close();rmSync(dir,{recursive:true,force:true})});
 const setup=await auth.setup({name:'Owner',username:'owner',password:'cash-recovery-fixture-password'});
 const session=auth.session(setup.token);
 const supplier=openSuppliers(store).create(session,{request_id:randomUUID(),code:'QA-RESTORE',name:'Restore supplier',currency:'IQD'}).supplier;
 const product=store.create({name:'Milk',sku:'MILK',currency:'IQD',unit_price:1700,unit_cost:900,carton_units:6,carton_price:10000,stock_milli:20000,barcodes:[]});
 const cash=openCash(store),purchases=openPurchases(store,{cash});
 store.attachSaleCashHook((actor,sale)=>cash.recordSale(actor,sale));
 cash.open(session,{request_id:randomUUID(),currency:'IQD',opening_amount:10000});
 store.sell({request_id:randomUUID(),currency:'IQD',received:2000,items:[{product_id:product.id,unit:'unit',quantity:1}]},setup.user.id);
 purchases.post(session,{request_id:randomUUID(),supplier_id:supplier.id,currency:'IQD',items:[{product_id:product.id,unit:'unit',quantity:3,unit_cost:1000}]});
 const canceled={request_id:randomUUID(),supplier_id:supplier.id,currency:'IQD',items:[{product_id:product.id,unit:'unit',quantity:1,unit_cost:1000}]};
 purchases.stage(session,canceled);purchases.cancelIntent(session,canceled.request_id);
 const pending={...canceled,request_id:randomUUID()};
 purchases.stage(session,pending);
 assert.equal(cash.status(session).shifts[0].balance,8700);
 assert.equal(reconcile(store.db).ok,true);
 const backup=await store.backup(join(live,'backups')),file=join(live,'backups',backup.name),beforeHash=hash(file);
 const checked=await openBackups(join(live,'backups')).verify(backup.name);
 assert.equal(checked.ok,true);assert.equal(checked.reconciliation.ok,true);
 const cashRows=store.db.prepare('SELECT * FROM cash_ledger ORDER BY rowid').all();
 const shiftRows=store.db.prepare('SELECT * FROM cash_shifts ORDER BY rowid').all();
 const pendingRows=store.db.prepare('SELECT * FROM purchase_intents ORDER BY rowid').all();
 const cancelRows=store.db.prepare('SELECT * FROM purchase_intent_cancellations ORDER BY rowid').all();
 const report=await prepareRecovery({backup:file,output:out,liveDataDir:live});
 assert.equal(report.reconciliation.ok,true);assert.equal(report.reconciliation.checked.cash_shifts,1);
 assert.equal(report.cloud_sync_enabled,false);assert.equal(report.requires_review,true);
 assert.equal(hash(file),beforeHash);assert.equal(existsSync(join(out,'sync-device.json')),false);
 const restored=openStore(join(out,'zhirox.sqlite'));
 try{
  const restoredAuth=openAuth(restored.db);
  assert.equal(restoredAuth.session(setup.token),null);
  const reauth=await restoredAuth.login({username:'owner',password:'cash-recovery-fixture-password'});
  const restoredSession=restoredAuth.session(reauth.token);
  const restoredCash=openCash(restored);
  const restoredPurchases=openPurchases(restored,{cash:restoredCash});
  assert.deepEqual(restored.db.prepare('SELECT * FROM cash_ledger ORDER BY rowid').all(),cashRows);
  assert.deepEqual(restored.db.prepare('SELECT * FROM cash_shifts ORDER BY rowid').all(),shiftRows);
  assert.deepEqual(restored.db.prepare('SELECT * FROM purchase_intents ORDER BY rowid').all(),pendingRows);
  assert.deepEqual(restored.db.prepare('SELECT * FROM purchase_intent_cancellations ORDER BY rowid').all(),cancelRows);
  assert.equal(restoredCash.status(restoredSession).shifts[0].balance,8700);
  assert.equal(restoredPurchases.listIntents(restoredSession).pending[0].request_id,pending.request_id);
  assert.equal(restoredPurchases.listIntents(restoredSession).pending.length,1);
  assert.equal(reconcile(restored.db).ok,true);
  assert.equal(restored.db.prepare("SELECT count(*) n FROM access_audit WHERE action='recovery.prepared'").get().n,1);
 }finally{restored.close();}
});
